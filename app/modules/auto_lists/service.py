"""Creates the daily curated lists, each under one of the site's own accounts
picked at random.

Lists are built from the knowledge graph itself (best-ranked titles of one
genre + one actor, or one genre + one decade), not generated by a model:
every title in a list really matches its heading, there is no API cost, and
no new dependency. Runs from app/core/periodic.py; safe on several instances
(advisory lock + a per-day marker count).

Each auto-made list carries `curation_note = "auto:<tehran day>:<slot>"`
(shown only in the admin panel); the number of markers for today is how many
were already made, so a restart never creates extras.
"""
import logging
import random
import uuid
from datetime import date, datetime, time, timezone

from sqlalchemy import func, select, text
from sqlalchemy.ext.asyncio import AsyncSession

from app.config import settings
from app.modules.auto_lists.texts import publish_hour, render_actor_list, render_decade_list
from app.modules.auto_lists.themes import find_theme
from app.modules.daily_battle.tehran import TEHRAN_TZ, tehran_today, utcnow
from app.modules.lists.models import UserList
from app.modules.lists.repository import ListRepository
from app.modules.lists.schemas import ListCreate
from app.modules.lists.service import ListService
from app.modules.users.models import User

logger = logging.getLogger(__name__)

_ADVISORY_KEY = 7_421_930_017
MIN_ITEMS = 6
MAX_ITEMS = 12
_ATTEMPTS = 12
MARKER_PREFIX = "auto:"


def tehran_day_start(day: date) -> datetime:
    """UTC instant of 00:00 Tehran on `day`."""
    return datetime.combine(day, time.min, tzinfo=TEHRAN_TZ).astimezone(timezone.utc)


def configured_emails() -> list[str]:
    """AUTO_LISTS_USER_EMAILS (comma separated); falls back to the single
    AUTO_LISTS_USER_EMAIL so an older setup keeps working."""
    raw = settings.auto_lists_user_emails or settings.auto_lists_user_email or ""
    seen: list[str] = []
    for email in raw.split(","):
        email = email.strip().lower()
        if email and email not in seen:
            seen.append(email)
    return seen


async def owners(db: AsyncSession) -> list[User]:
    """The active accounts among the configured emails, sorted by email so a
    seeded random pick is reproducible."""
    emails = configured_emails()
    if not emails:
        return []
    stmt = (
        select(User)
        .where(func.lower(User.email).in_(emails), User.deleted_at.is_(None), User.is_active.is_(True))
        .order_by(User.email)
    )
    found = list((await db.execute(stmt)).scalars().all())
    missing = set(emails) - {u.email.lower() for u in found}
    if missing:
        logger.warning("auto content: no active user for %s", ", ".join(sorted(missing)))
    return found


def pick_owner(users: list[User], day: date, slot: int, salt: str) -> User:
    return random.Random(f"{day.isoformat()}:{slot}:{salt}").choice(users)


async def _made_today(db: AsyncSession, day: date) -> int:
    stmt = select(func.count(UserList.id)).where(UserList.curation_note.like(f"{MARKER_PREFIX}{day.isoformat()}:%"))
    return (await db.execute(stmt)).scalar_one()


async def _tags_used(db: AsyncSession, user_ids: list[uuid.UUID], tags: list[str]) -> bool:
    stmt = select(UserList.id).where(UserList.user_id.in_(user_ids), UserList.tags.contains(tags)).limit(1)
    return (await db.execute(stmt)).first() is not None


async def create_daily_list(db: AsyncSession, now: datetime | None = None) -> UserList | None:
    """Create the next of today's lists when it is due; returns it, or None
    when nothing was created (disabled, too early, quota reached, or no
    usable theme)."""
    if not settings.auto_lists_enabled:
        return None
    now = now or utcnow()
    day = tehran_today(now)

    got = (await db.execute(text("SELECT pg_try_advisory_xact_lock(:k)"), {"k": _ADVISORY_KEY})).scalar_one()
    if not got:
        await db.rollback()
        return None

    slot = await _made_today(db, day)
    if slot >= settings.auto_lists_per_day or now.astimezone(TEHRAN_TZ).hour < publish_hour(day, slot):
        await db.rollback()
        return None

    users = await owners(db)
    if not users:
        logger.warning("auto lists: no active user among %s", configured_emails())
        await db.rollback()
        return None
    owner = pick_owner(users, day, slot, "list")
    owner_ids = [u.id for u in users]

    async def is_used(_key: str, tags: list[str]) -> bool:
        return await _tags_used(db, owner_ids, tags)

    theme = None
    rng = random.Random(f"{day.isoformat()}:{slot}:list-theme")
    for _ in range(_ATTEMPTS):
        wanted = rng.randint(MIN_ITEMS + 1, MAX_ITEMS)
        theme = await find_theme(db, rng, min_items=MIN_ITEMS, pool_size=wanted, is_used=is_used)
        if theme:
            break
    if theme is None:
        logger.warning("auto lists: no usable theme found for %s", day)
        await db.rollback()
        return None

    if theme.kind == "actor":
        title, description = render_actor_list(rng, theme.person_fa, theme.genre_fa, len(theme.movies))
    else:
        title, description = render_decade_list(rng, theme.decade, theme.genre_fa, len(theme.movies))

    service = ListService(db)
    repo = ListRepository(db)
    # Built as a private draft and published once every item is in, so a
    # half-filled list is never visible.
    lst = await service.create_list(
        owner.id,
        ListCreate(title=title, description=description, entity_type="movie", tags=theme.tags, visibility="private"),
    )
    for position, movie in enumerate(theme.movies, start=1):
        await repo.add_item(lst.id, movie.id, movie.entity_type, None, position, added_by_user_id=owner.id)
    lst.curation_note = f"{MARKER_PREFIX}{day.isoformat()}:{slot}"
    await repo.update_list(lst, visibility="public")
    await repo.touch(lst.id)
    await db.commit()
    logger.info("auto lists: created %s for %s (%d items)", lst.slug, owner.email, len(theme.movies))
    return lst
