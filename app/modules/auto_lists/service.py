"""Creates the daily curated list under the site's own account.

Lists are built from the knowledge graph itself (best-ranked titles of one
genre + one actor, or one genre + one decade), not generated by a model:
every title in a list really matches its heading, there is no API cost, and
no new dependency. Runs from app/core/periodic.py; safe on several instances
(advisory lock + a per-day count check).
"""
import logging
import random
import uuid
from datetime import date, datetime, time, timezone

from sqlalchemy import func, select, text
from sqlalchemy.ext.asyncio import AsyncSession

from app.config import settings
from app.modules.auto_lists.texts import (
    GENRE_FA, publish_hour, render_actor_list, render_decade_list, decade_label,
)
from app.modules.daily_battle.tehran import TEHRAN_TZ, tehran_today, utcnow
from app.modules.entities.models import Entity, EntityRanking, PersonStats, RelationshipEdge
from app.modules.lists.models import UserList
from app.modules.lists.repository import ListRepository
from app.modules.lists.schemas import ListCreate
from app.modules.lists.service import ListService
from app.modules.users.models import User

logger = logging.getLogger(__name__)

_ADVISORY_KEY = 7_421_930_017
MIN_ITEMS = 6
MAX_ITEMS = 12
_ATTEMPTS = 12
# Actors with at least this many credited works are candidates.
_MIN_ACTOR_WORKS = 12
_ACTOR_POOL = 200
DECADES = (1970, 1980, 1990, 2000, 2010)


def tehran_day_start(day: date) -> datetime:
    """UTC instant of 00:00 Tehran on `day`."""
    return datetime.combine(day, time.min, tzinfo=TEHRAN_TZ).astimezone(timezone.utc)


async def _owner(db: AsyncSession) -> User | None:
    email = (settings.auto_lists_user_email or "").strip().lower()
    if not email:
        return None
    stmt = select(User).where(func.lower(User.email) == email, User.deleted_at.is_(None), User.is_active.is_(True))
    return (await db.execute(stmt)).scalar_one_or_none()


async def _already_made_today(db: AsyncSession, user_id: uuid.UUID, day: date) -> int:
    stmt = select(func.count(UserList.id)).where(
        UserList.user_id == user_id,
        UserList.is_watch_later.is_(False),
        UserList.created_at >= tehran_day_start(day),
    )
    return (await db.execute(stmt)).scalar_one()


async def _tag_pair_exists(db: AsyncSession, user_id: uuid.UUID, tags: list[str]) -> bool:
    stmt = select(UserList.id).where(UserList.user_id == user_id, UserList.tags.contains(tags)).limit(1)
    return (await db.execute(stmt)).first() is not None


async def _genres(db: AsyncSession) -> list[Entity]:
    stmt = select(Entity).where(Entity.entity_type == "genre", func.lower(Entity.title).in_(list(GENRE_FA)))
    return list((await db.execute(stmt)).scalars().all())


def _ranked_movies(stmt, limit: int):
    return (
        stmt.outerjoin(EntityRanking, EntityRanking.entity_id == Entity.id)
        .where(Entity.entity_type == "movie", EntityRanking.computed_score.is_not(None))
        .order_by(EntityRanking.computed_score.desc(), Entity.title)
        .limit(limit)
    )


async def _actor_genre_movies(db: AsyncSession, person_id: uuid.UUID, genre_id: uuid.UUID, limit: int) -> list[Entity]:
    """Best-ranked movies in which `person_id` acted (cast credit only) and
    that carry the genre."""
    acted = select(RelationshipEdge.from_entity_id).where(
        RelationshipEdge.to_entity_id == person_id, RelationshipEdge.relation_type == "acted_in"
    )
    tagged = select(RelationshipEdge.from_entity_id).where(
        RelationshipEdge.to_entity_id == genre_id, RelationshipEdge.relation_type == "has_genre"
    )
    stmt = select(Entity).where(Entity.id.in_(acted), Entity.id.in_(tagged))
    return list((await db.execute(_ranked_movies(stmt, limit))).scalars().all())


async def _decade_genre_movies(db: AsyncSession, genre_id: uuid.UUID, decade: int, limit: int) -> list[Entity]:
    tagged = select(RelationshipEdge.from_entity_id).where(
        RelationshipEdge.to_entity_id == genre_id, RelationshipEdge.relation_type == "has_genre"
    )
    stmt = select(Entity).where(
        Entity.id.in_(tagged),
        Entity.attributes["year"].as_integer().between(decade, decade + 9),
    )
    return list((await db.execute(_ranked_movies(stmt, limit))).scalars().all())


async def _pick_actor(db: AsyncSession, rng: random.Random) -> Entity | None:
    """A well-known actor with a Persian name, from the people ranking table."""
    stmt = (
        select(Entity)
        .join(PersonStats, PersonStats.person_id == Entity.id)
        .where(
            PersonStats.role == "actor", PersonStats.origin == "all",
            PersonStats.works >= _MIN_ACTOR_WORKS,
            Entity.attributes["title_fa"].as_string().is_not(None),
        )
        .order_by(PersonStats.works.desc())
        .limit(_ACTOR_POOL)
    )
    people = list((await db.execute(stmt)).scalars().all())
    return rng.choice(people) if people else None


async def _build_theme(db: AsyncSession, user_id: uuid.UUID, day: date, attempt: int):
    """One candidate (title, description, tags, movies), or None when this
    attempt found nothing usable (too few titles, or already done before)."""
    rng = random.Random(f"{day.isoformat()}:{attempt}")
    genres = await _genres(db)
    if not genres:
        return None
    genre = rng.choice(genres)
    genre_fa = GENRE_FA[genre.title.lower()]
    wanted = rng.randint(MIN_ITEMS + 1, MAX_ITEMS)

    if rng.random() < 0.7:
        person = await _pick_actor(db, rng)
        if person is None:
            return None
        name = (person.attributes or {}).get("title_fa")
        tags = [genre_fa, name]
        if await _tag_pair_exists(db, user_id, tags):
            return None
        movies = await _actor_genre_movies(db, person.id, genre.id, wanted)
        if len(movies) < MIN_ITEMS:
            return None
        title, description = render_actor_list(rng, name, genre_fa, len(movies))
        return title, description, tags, movies

    decade = rng.choice(DECADES)
    tags = [genre_fa, f"دهه {decade_label(decade)}"]
    if await _tag_pair_exists(db, user_id, tags):
        return None
    movies = await _decade_genre_movies(db, genre.id, decade, wanted)
    if len(movies) < MIN_ITEMS:
        return None
    title, description = render_decade_list(rng, decade, genre_fa, len(movies))
    return title, description, tags, movies


async def create_daily_list(db: AsyncSession, now: datetime | None = None) -> UserList | None:
    """Create today's list when it is due; returns it, or None when nothing was
    created (disabled, too early, already made, or no usable theme)."""
    if not settings.auto_lists_enabled:
        return None
    now = now or utcnow()
    day = tehran_today(now)
    if now.astimezone(TEHRAN_TZ).hour < publish_hour(day):
        return None

    got = (await db.execute(text("SELECT pg_try_advisory_xact_lock(:k)"), {"k": _ADVISORY_KEY})).scalar_one()
    if not got:
        await db.rollback()
        return None

    owner = await _owner(db)
    if owner is None:
        logger.warning("auto lists: no active user with email %r", settings.auto_lists_user_email)
        await db.rollback()
        return None
    if await _already_made_today(db, owner.id, day) >= settings.auto_lists_per_day:
        await db.rollback()
        return None

    theme = None
    for attempt in range(_ATTEMPTS):
        theme = await _build_theme(db, owner.id, day, attempt)
        if theme:
            break
    if theme is None:
        logger.warning("auto lists: no usable theme found for %s", day)
        await db.rollback()
        return None
    title, description, tags, movies = theme

    service = ListService(db)
    repo = ListRepository(db)
    # Built as a private draft and published once every item is in, so a
    # half-filled list is never visible.
    lst = await service.create_list(
        owner.id,
        ListCreate(title=title, description=description, entity_type="movie", tags=tags, visibility="private"),
    )
    for position, movie in enumerate(movies, start=1):
        await repo.add_item(lst.id, movie.id, movie.entity_type, None, position, added_by_user_id=owner.id)
    await repo.update_list(lst, visibility="public")
    await repo.touch(lst.id)
    await db.commit()
    logger.info("auto lists: created %s (%d items)", lst.slug, len(movies))
    return lst
